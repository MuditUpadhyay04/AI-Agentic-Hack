"""AI4I 2020: load the real file, or build a replica from its published generation rules.

The real dataset (UCI 601, CC BY 4.0) is itself synthetic, generated by the rules described on its UCI
page. ``scripts/fetch_data.py`` downloads it into ``data/ai4i2020.csv``; when that file is missing (no
internet), ``load()`` builds a replica with the same columns and the same failure rules, seeded, and says
so in ``source``. Every number PitCrew reports carries that source.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .mill import HDF_DT_K, HDF_RPM, OSF_LIMIT, PWF_MAX_W, PWF_MIN_W, WEAR_PER_PART

DATA = Path(__file__).resolve().parents[1] / "data"
REAL = DATA / "ai4i2020.csv"
COLUMNS = ["UDI", "Product ID", "Type", "Air temperature [K]", "Process temperature [K]",
           "Rotational speed [rpm]", "Torque [Nm]", "Tool wear [min]", "Machine failure",
           "TWF", "HDF", "PWF", "OSF", "RNF"]


def _walk(rng, n: int, sd: float) -> np.ndarray:
    w = np.cumsum(rng.normal(0, 1, n))
    w = (w - w.mean()) / w.std()
    return w * sd


def generate_replica(n: int = 10000, seed: int = 2020) -> pd.DataFrame:
    """Same columns and failure rules as AI4I 2020 (UCI 601), from its documented generation process."""
    rng = np.random.default_rng(seed)
    types = rng.choice(["L", "M", "H"], size=n, p=[0.5, 0.3, 0.2])
    air = 300.0 + _walk(rng, n, 2.0)
    process = air + 10.0 + _walk(rng, n, 1.0)  # gap from its own walk (sd 1 K)
    torque = np.clip(rng.normal(40.0, 10.0, n), 3.8, None)
    # speed falls as torque rises (power roughly constant per process) with noise; real data: mean 1,539 rpm
    rpm = np.clip(1560.0 * (40.0 / torque) ** 0.40 * np.exp(rng.normal(0, 0.045, n)), 1168, 2886)
    wear = np.zeros(n)
    twf = np.zeros(n, dtype=int)
    w, limit = 0.0, rng.uniform(200, 240)
    for i in range(n):
        w += WEAR_PER_PART[types[i]]
        wear[i] = w
        if w >= limit:  # the tool is replaced, or fails (51 of 120 in the real data)
            if rng.random() < 51 / 120:
                twf[i] = 1
            w, limit = 0.0, rng.uniform(200, 240)
    power = torque * rpm * 2 * np.pi / 60
    hdf = ((process - air) < HDF_DT_K) & (rpm < HDF_RPM)
    pwf = (power < PWF_MIN_W) | (power > PWF_MAX_W)
    osf = wear * torque > np.array([OSF_LIMIT[t] for t in types])
    rnf = rng.random(n) < 0.001
    df = pd.DataFrame({
        "UDI": np.arange(1, n + 1),
        "Product ID": [f"{t}{47181 + i}" for i, t in enumerate(types)],
        "Type": types,
        "Air temperature [K]": air.round(1),
        "Process temperature [K]": process.round(1),
        "Rotational speed [rpm]": rpm.round().astype(int),
        "Torque [Nm]": torque.round(1),
        "Tool wear [min]": wear.round().astype(int),
        "TWF": twf, "HDF": hdf.astype(int), "PWF": pwf.astype(int), "OSF": osf.astype(int),
        "RNF": rnf.astype(int),
    })
    df["Machine failure"] = (df[["TWF", "HDF", "PWF", "OSF", "RNF"]].sum(axis=1) > 0).astype(int)
    return df[COLUMNS]


def load(prefer_real: bool = True) -> tuple[pd.DataFrame, str]:
    """(dataframe, source). The real UCI file when present, else the seeded replica (cached)."""
    if prefer_real and REAL.exists():
        return pd.read_csv(REAL), "AI4I 2020, UCI dataset 601 (real file)"
    cache = DATA / "ai4i2020_replica.csv"
    if cache.exists():
        df = pd.read_csv(cache)
    else:
        df = generate_replica()
        DATA.mkdir(exist_ok=True)
        df.to_csv(cache, index=False)
    return df, "AI4I 2020 replica (published rules, seed 2020) - run scripts/fetch_data.py for the real file"


def add_physics(df: pd.DataFrame) -> pd.DataFrame:
    """Columns the walls are written in: power, strain, temperature gap, the variant's strain limit."""
    out = df.copy()
    out["power_w"] = out["Torque [Nm]"] * out["Rotational speed [rpm]"] * 2 * np.pi / 60
    out["strain"] = out["Tool wear [min]"] * out["Torque [Nm]"]
    out["d_temp"] = out["Process temperature [K]"] - out["Air temperature [K]"]
    out["osf_limit"] = out["Type"].map(OSF_LIMIT)
    out["strain_ratio"] = out["strain"] / out["osf_limit"]
    return out
